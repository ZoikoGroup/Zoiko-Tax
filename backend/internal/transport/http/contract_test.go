// testRouter is the surface with no services behind it.
//
// Every test here is about routing, authentication shape and error shape, none
// of which reaches a service: an unrouted path never gets that far, a probe
// touches nothing, and a request with no session cookie is refused by the
// middleware. Wiring real services in would make these tests depend on a
// database to assert something about a route table.
func testRouter() *ztaxhttp.Router {
	return ztaxhttp.NewRouter(nil, nil, nil, nil, slog.New(slog.DiscardHandler), idgen.V7{})
}

// The contract's route table, generated by contracts/tools/routes.mjs and
// hash-checked, so this test cannot be reading a kinder statement of the
// surface than the one the SDKs are generated from.
//
// The path climbs out of the Go module because contracts/ is a repository class
// of its own with its own CODEOWNERS and its own pipeline (ADR-0007 §2.1, §2.2).
// It sits beside backend/ rather than inside it, and a copy inside the module
// would be a second contract.
const routesManifest = "../../../../contracts/openapi/export/ztax.v1.routes.json"

// Health probes are served and are deliberately not in the contract. Putting
// them there would generate SDK methods nobody should call and would make a
// liveness probe a compatibility commitment governed by ADR-0010 §2.6.
//
// This list is the exception register. It is short, it is here rather than in a
// flag somewhere, and anything added to it is a route that will never appear in
// a customer's SDK — which is a decision, not an oversight.
var notInContract = map[string]bool{
	"GET /healthz": true,
	"GET /readyz":  true,
}

type contractRoute struct {
	Method      string `json:"method"`
	Path        string `json:"path"`
	OperationID string `json:"operationId"`
	Public      bool   `json:"public"`
}

func loadContractRoutes(t *testing.T) map[string]contractRoute {
	t.Helper()
	data, err := os.ReadFile(filepath.Clean(routesManifest))
	if err != nil {
		t.Fatalf("read %s: %v\nRun `npm run routes` in contracts/.", routesManifest, err)
	}
	var doc struct {
		Routes []contractRoute `json:"routes"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		t.Fatalf("decode %s: %v", routesManifest, err)
	}
	if len(doc.Routes) == 0 {
		t.Fatalf("%s declares no routes", routesManifest)
	}

	out := make(map[string]contractRoute, len(doc.Routes))
	for _, r := range doc.Routes {
		out[r.Method+" "+r.Path] = r
	}
	return out
}

// TestServerMatchesContract is ADR-0010 §2.1's drift gate, discharged from the
// server side until the handlers are generated.
//
// It runs in both directions on purpose. A route the server serves and the
// contract does not declare is a surface nobody reviewed and no SDK reaches. A
// route the contract declares and the server does not serve is worse: five
// generated SDKs have a method for it, and every caller of that method gets a
// 404 that looks like their mistake.
func TestServerMatchesContract(t *testing.T) {
	contract := loadContractRoutes(t)
	router := testRouter()

	served := map[string]ztaxhttp.Route{}
	for _, r := range router.Routes() {
		key := r.Method + " " + r.Pattern
		if _, dup := served[key]; dup {
			t.Errorf("the router declares %s twice", key)
		}
		served[key] = r
	}

	t.Run("every served route is in the contract", func(t *testing.T) {
		for _, key := range sortedKeys(served) {
			if notInContract[key] {
				continue
			}
			if _, ok := contract[key]; !ok {
				t.Errorf("%s is served and is not in the contract; an undocumented endpoint is a surface nobody reviewed", key)
			}
		}
	})

	t.Run("every contract route is served", func(t *testing.T) {
		for _, key := range sortedContract(contract) {
			if _, ok := served[key]; !ok {
				t.Errorf("%s is in the contract and nothing routes it; the generated SDKs have a method that cannot work", key)
			}
		}
	})

	t.Run("authentication agrees with the contract", func(t *testing.T) {
		for _, key := range sortedContract(contract) {
			want := contract[key]
			got, ok := served[key]
			if !ok {
				continue // Already reported above.
			}
			if got.Public != want.Public {
				// The two failures are not symmetric and both are serious: an
				// endpoint the contract publishes as open and the server closes
				// breaks integrations in production; the reverse serves without
				// a session.
				t.Errorf("%s (%s): the contract says public=%v, the server says public=%v",
					key, want.OperationID, want.Public, got.Public)
			}
		}
	})
}

// TestUnroutedPathsAreProblems checks that the surface's error shape holds even
// where there is no handler. ADR-0016 §2.5: every error a client sees has the
// same shape, including the one ServeMux would otherwise answer with plain text.
func TestUnroutedPathsAreProblems(t *testing.T) {
	handler := testRouter().Handler()

	for _, path := range []string{"/v1/does-not-exist", "/", "/v1/admin"} {
		t.Run(path, func(t *testing.T) {
			rec := httptest.NewRecorder()
			handler.ServeHTTP(rec, httptest.NewRequest(nethttp.MethodGet, path, nil))

			if rec.Code != nethttp.StatusNotFound {
				t.Fatalf("status %d, want 404", rec.Code)
			}
			if ct := rec.Header().Get("Content-Type"); ct != "application/problem+json" {
				t.Errorf("Content-Type %q, want application/problem+json", ct)
			}

			var problem struct {
				Type       string `json:"type"`
				Status     int    `json:"status"`
				ReasonCode string `json:"ztx_reason_code"`
				Retryable  bool   `json:"ztx_retryable"`
			}
			if err := json.Unmarshal(rec.Body.Bytes(), &problem); err != nil {
				t.Fatalf("body is not JSON: %v", err)
			}
			if problem.ReasonCode != "NOT_FOUND" {
				t.Errorf("reason code %q, want NOT_FOUND", problem.ReasonCode)
			}
			if problem.Status != nethttp.StatusNotFound {
				t.Errorf("problem status %d, want 404", problem.Status)
			}
			if problem.Retryable {
				t.Error("a 404 is not retryable; a client that retries it is generating load")
			}
			if !strings.HasPrefix(problem.Type, ztaxhttp.ProblemBaseURI) {
				t.Errorf("type %q does not resolve under %s", problem.Type, ztaxhttp.ProblemBaseURI)
			}
		})
	}
}

// TestHealthProbesAreNotAContract guards the exception register above: the
// probes must keep working and must keep being plain text, because an
// orchestrator reads them and nothing generated from the contract does.
func TestHealthProbesAreNotAContract(t *testing.T) {
	handler := testRouter().Handler()

	for path, want := range map[string]string{"/healthz": "ok\n", "/readyz": "ready\n"} {
		t.Run(path, func(t *testing.T) {
			rec := httptest.NewRecorder()
			handler.ServeHTTP(rec, httptest.NewRequest(nethttp.MethodGet, path, nil))
			if rec.Code != nethttp.StatusOK {
				t.Fatalf("status %d, want 200", rec.Code)
			}
			if rec.Body.String() != want {
				t.Errorf("body %q, want %q", rec.Body.String(), want)
			}
			if ct := rec.Header().Get("Content-Type"); !strings.HasPrefix(ct, "text/plain") {
				t.Errorf("Content-Type %q, want text/plain", ct)
			}
		})
	}
}

func sortedKeys(m map[string]ztaxhttp.Route) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func sortedContract(m map[string]contractRoute) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
